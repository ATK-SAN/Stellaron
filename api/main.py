"""STELLARON FastAPI server.

Serves precomputed static results from data/processed/.
No live computation on request — all results are pre-generated by precompute/generate_library.py.
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.staticfiles import StaticFiles

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_PROCESSED = BASE_DIR / "data" / "processed"
SITES_PATH = BASE_DIR / "data" / "sites.json"

app = FastAPI(
    title="STELLARON API",
    description="Lunar landing-site navigator — pre-computed science results (NASA Space Apps 2026).",
    version="2.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET"],
    allow_headers=["*"],
)


def _load_json(path: Path) -> Any:
    if not path.exists():
        raise HTTPException(status_code=404, detail=f"File not found: {path.name}")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


@app.get("/health")
def health() -> Dict[str, str]:
    return {"status": "ok", "version": "2.0.0"}


@app.get("/sites", response_model=List[Dict[str, Any]])
def list_sites() -> List[Dict[str, Any]]:
    """Return all 14 library sites with metadata."""
    return _load_json(SITES_PATH)


@app.get("/library", response_model=Dict[str, Any])
def library_index() -> Dict[str, Any]:
    """Return the full library index with computed metrics for all sites."""
    index_path = DATA_PROCESSED / "library_index.json"
    return _load_json(index_path)


@app.get("/run/{site_id}", response_model=Dict[str, Any])
def get_run(site_id: str) -> Dict[str, Any]:
    """Return precomputed science run for a specific site (2026-04 to 2026-05)."""
    # Sanitise site_id to prevent path traversal
    if not site_id.replace("_", "").isalnum():
        raise HTTPException(status_code=400, detail="Invalid site_id")
    result_path = DATA_PROCESSED / f"{site_id}_2026.json"
    return _load_json(result_path)


@app.get("/run/{site_id}/metrics", response_model=Dict[str, Any])
def get_metrics(site_id: str) -> Dict[str, Any]:
    """Return only the metrics section of a site run (smaller payload)."""
    full = get_run(site_id)
    return {
        "site_id": full["site_id"],
        "run_id": full["run_id"],
        "metrics": full["metrics"],
        "provenance": full["provenance"],
    }


@app.get("/run/{site_id}/provenance", response_model=Dict[str, Any])
def get_provenance(site_id: str) -> Dict[str, Any]:
    """Return provenance record for a site run (kernels, SHA-256, assumptions)."""
    full = get_run(site_id)
    return full["provenance"]


@app.get("/agreement", response_model=Dict[str, Any])
def get_agreement() -> Dict[str, Any]:
    """Return the visual/science agreement benchmark result."""
    return _load_json(DATA_PROCESSED / "agreement_benchmark.json")
